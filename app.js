let currentChapter = 1;

function showChapter(num) {
    currentChapter = num;
    const chapter = chapters[num];
    const content = document.getElementById('content');
    const toc = document.getElementById('toc');
    
    toc.classList.add('hidden');
    
    let html = `<div class="chapter"><h2>${chapter.title}</h2>`;
    
    chapter.paragraphs.forEach(p => {
        html += `<div class="paragraph"><h3>${p.title}</h3>`;
        html += `<p>${p.text.replace(/\n/g, '</p><p>')}</p>`;
        
        if (p.quote) {
            html += `<div class="quote">${p.quote}</div>`;
        }
        
        if (p.questions) {
            html += `<div class="questions"><h4>📝 Вопросы для закрепления</h4><ol>`;
            p.questions.forEach(q => html += `<li>${q}</li>`);
            html += `</ol></div>`;
        }
        
        if (p.conclusion) {
            html += `<div class="conclusion">📌 ${p.conclusion}</div>`;
        }
        
        html += `</div>`;
    });
    
    html += `<div class="nav-buttons">`;
    if (num > 1) {
        html += `<button onclick="showChapter(${num - 1})">← Назад</button>`;
    }
    html += `<button onclick="showTOC()">📖 Содержание</button>`;
    if (num < 6) {
        html += `<button onclick="showChapter(${num + 1})">Вперёд →</button>`;
    }
    html += `</div></div>`;
    
    content.innerHTML = html;
    window.scrollTo(0, 0);
}

function showTOC() {
    document.getElementById('toc').classList.remove('hidden');
    document.getElementById('content').innerHTML = '';
} 
